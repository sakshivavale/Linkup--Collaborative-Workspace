import { useEffect, useRef, useState, useCallback } from 'react';
import { socket } from '../../lib/socket';
import { Participant } from './participantUtils';

export const ICE_SERVERS: RTCConfiguration = {
  iceServers: [
    { urls: 'stun:stun.l.google.com:19302' },
    { urls: 'stun:stun1.l.google.com:19302' },
    { urls: 'stun:stun2.l.google.com:19302' },
    { urls: 'stun:stun3.l.google.com:19302' },
    { urls: 'stun:stun4.l.google.com:19302' },
    { urls: 'stun:global.stun.twilio.com:3478' },
  ],
  iceCandidatePoolSize: 10,
};

interface UsePeerConnectionsOptions {
  roomId: string;
  currentUserId?: string;
  inCall: boolean;
  participants: Participant[];
  localStream: MediaStream | null;
  camOn: boolean;
  micOn: boolean;
}

export function usePeerConnections({
  roomId,
  currentUserId,
  inCall,
  participants,
  localStream,
  camOn,
  micOn,
}: UsePeerConnectionsOptions) {
  // Map of remote userId -> MediaStream received from peer
  const [remoteStreams, setRemoteStreams] = useState<Map<string, MediaStream>>(new Map());

  // RTCPeerConnections keyed by remote userId
  const peerConnectionsRef = useRef<Map<string, RTCPeerConnection>>(new Map());
  // Pending ICE candidates received before remote description was ready
  const pendingIceCandidatesRef = useRef<Map<string, RTCIceCandidateInit[]>>(new Map());

  // Refs for current media states so async callbacks access latest tracks without recreation
  const localStreamRef = useRef<MediaStream | null>(localStream);
  localStreamRef.current = localStream;
  const camOnRef = useRef<boolean>(camOn);
  camOnRef.current = camOn;
  const micOnRef = useRef<boolean>(micOn);
  micOnRef.current = micOn;

  /**
   * Helper to attach or replace tracks on a given RTCPeerConnection
   */
  const syncLocalTracksToPeer = useCallback((pc: RTCPeerConnection) => {
    const stream = localStreamRef.current;
    const isCam = camOnRef.current;
    const isMic = micOnRef.current;

    const audioTrack = isMic && stream ? stream.getAudioTracks()[0] ?? null : null;
    const videoTrack = isCam && stream ? stream.getVideoTracks()[0] ?? null : null;

    const senders = pc.getSenders();

    // 1. Audio track sync
    const audioSender = senders.find(
      (s) => s.track?.kind === 'audio' || (!s.track && (s as any).trackType === 'audio')
    );
    if (audioSender) {
      audioSender.replaceTrack(audioTrack).catch((err) => {
        console.warn('[WebRTC] Error replacing audio track:', err);
      });
    }

    // 2. Video track sync
    const videoSender = senders.find(
      (s) => s.track?.kind === 'video' || (!s.track && (s as any).trackType === 'video')
    );
    if (videoSender) {
      videoSender.replaceTrack(videoTrack).catch((err) => {
        console.warn('[WebRTC] Error replacing video track:', err);
      });
    }
  }, []);

  /**
   * Create and configure an RTCPeerConnection for a remote peer
   */
  const createPeerConnection = useCallback(
    (remoteUserId: string): RTCPeerConnection => {
      console.log(`[WebRTC] Creating RTCPeerConnection for user: ${remoteUserId}`);
      const pc = new RTCPeerConnection(ICE_SERVERS);
      peerConnectionsRef.current.set(remoteUserId, pc);

      // Add bidirectional transceivers so senders exist immediately
      const audioTransceiver = pc.addTransceiver('audio', { direction: 'sendrecv' });
      const videoTransceiver = pc.addTransceiver('video', { direction: 'sendrecv' });

      // Tag senders so we can identify them even when track is null
      (audioTransceiver.sender as any).trackType = 'audio';
      (videoTransceiver.sender as any).trackType = 'video';

      // Attach current local tracks if active
      const stream = localStreamRef.current;
      if (micOnRef.current && stream) {
        const aTrack = stream.getAudioTracks()[0];
        if (aTrack) audioTransceiver.sender.replaceTrack(aTrack).catch(() => {});
      }
      if (camOnRef.current && stream) {
        const vTrack = stream.getVideoTracks()[0];
        if (vTrack) videoTransceiver.sender.replaceTrack(vTrack).catch(() => {});
      }

      // Handle ICE candidates generated by this browser
      pc.onicecandidate = (event) => {
        if (event.candidate) {
          socket.emit('webrtc:ice-candidate', {
            roomId,
            targetUserId: remoteUserId,
            candidate: event.candidate.toJSON(),
            streamType: 'video',
          });
        }
      };

      // Handle incoming remote media tracks
      pc.ontrack = (event) => {
        console.log(`[WebRTC] Received remote track (${event.track.kind}) from ${remoteUserId}`);
        setRemoteStreams((prev) => {
          const next = new Map(prev);
          const existing = next.get(remoteUserId);
          if (existing) {
            if (!existing.getTracks().some((t) => t.id === event.track.id)) {
              existing.addTrack(event.track);
            }
            next.set(remoteUserId, new MediaStream(existing.getTracks()));
          } else {
            const newStream = event.streams[0] || new MediaStream([event.track]);
            next.set(remoteUserId, newStream);
          }
          return next;
        });

        event.track.onended = () => {
          console.log(`[WebRTC] Remote track ended (${event.track.kind}) from ${remoteUserId}`);
        };
      };

      pc.onconnectionstatechange = () => {
        console.log(`[WebRTC] Connection state to ${remoteUserId}: ${pc.connectionState}`);
        if (pc.connectionState === 'failed') {
          try {
            pc.restartIce();
          } catch {
            // Ignore
          }
        }
      };

      return pc;
    },
    [roomId]
  );

  /**
   * Whenever localStream, camOn, or micOn changes, sync tracks across all active peer connections
   */
  useEffect(() => {
    peerConnectionsRef.current.forEach((pc) => {
      syncLocalTracksToPeer(pc);
    });
  }, [localStream, camOn, micOn, syncLocalTracksToPeer]);

  /**
   * Main peer lifecycle effect:
   * Sets up socket signaling listeners for video calls and initiates connections to in-call peers
   */
  useEffect(() => {
    if (!inCall || !roomId || !currentUserId) {
      // Clean up all peer connections if user leaves call
      peerConnectionsRef.current.forEach((pc) => pc.close());
      peerConnectionsRef.current.clear();
      pendingIceCandidatesRef.current.clear();
      setRemoteStreams(new Map());
      return;
    }

    // Handle incoming video offer from another peer
    const onOffer = async (data: {
      roomId: string;
      sdp: RTCSessionDescriptionInit;
      fromSocketId: string;
      fromUserId?: string;
      streamType?: string;
    }) => {
      if (data.roomId !== roomId) return;
      if (data.streamType && data.streamType !== 'video') return; // Ignore screen share offers

      const peerUserId = data.fromUserId;
      if (!peerUserId || peerUserId === currentUserId) return;

      console.log(`[WebRTC] Received video offer from ${peerUserId}`);
      let pc = peerConnectionsRef.current.get(peerUserId);
      if (!pc || pc.signalingState === 'closed') {
        pc = createPeerConnection(peerUserId);
      }

      try {
        await pc.setRemoteDescription(new RTCSessionDescription(data.sdp));

        // Flush any buffered candidates for this peer
        const buffered = pendingIceCandidatesRef.current.get(peerUserId) || [];
        for (const candidate of buffered) {
          await pc.addIceCandidate(new RTCIceCandidate(candidate)).catch(() => {});
        }
        pendingIceCandidatesRef.current.delete(peerUserId);

        syncLocalTracksToPeer(pc);

        const answer = await pc.createAnswer();
        await pc.setLocalDescription(answer);

        socket.emit('webrtc:answer', {
          roomId,
          targetUserId: peerUserId,
          targetSocketId: data.fromSocketId,
          sdp: answer,
          streamType: 'video',
        });
        console.log(`[WebRTC] Sent video answer to ${peerUserId}`);
      } catch (err) {
        console.warn(`[WebRTC] Failed to handle offer from ${peerUserId}:`, err);
      }
    };

    // Handle incoming video answer
    const onAnswer = async (data: {
      roomId: string;
      sdp: RTCSessionDescriptionInit;
      fromSocketId: string;
      fromUserId?: string;
      streamType?: string;
    }) => {
      if (data.roomId !== roomId) return;
      if (data.streamType && data.streamType !== 'video') return;

      const peerUserId = data.fromUserId;
      if (!peerUserId || peerUserId === currentUserId) return;

      console.log(`[WebRTC] Received video answer from ${peerUserId}`);
      const pc = peerConnectionsRef.current.get(peerUserId);
      if (!pc || pc.signalingState === 'closed') return;

      try {
        await pc.setRemoteDescription(new RTCSessionDescription(data.sdp));

        // Flush buffered candidates
        const buffered = pendingIceCandidatesRef.current.get(peerUserId) || [];
        for (const candidate of buffered) {
          await pc.addIceCandidate(new RTCIceCandidate(candidate)).catch(() => {});
        }
        pendingIceCandidatesRef.current.delete(peerUserId);
      } catch (err) {
        console.warn(`[WebRTC] Failed to apply answer from ${peerUserId}:`, err);
      }
    };

    // Handle incoming ICE candidate
    const onIceCandidate = async (data: {
      roomId: string;
      candidate: RTCIceCandidateInit;
      fromSocketId: string;
      fromUserId?: string;
      streamType?: string;
    }) => {
      if (data.roomId !== roomId) return;
      if (data.streamType && data.streamType !== 'video') return;

      const peerUserId = data.fromUserId;
      if (!peerUserId || peerUserId === currentUserId) return;

      const pc = peerConnectionsRef.current.get(peerUserId);
      if (pc && pc.remoteDescription && pc.remoteDescription.type) {
        try {
          await pc.addIceCandidate(new RTCIceCandidate(data.candidate));
        } catch {
          // Ignore stale candidate
        }
      } else {
        // Buffer candidate until remote description is set
        const queue = pendingIceCandidatesRef.current.get(peerUserId) || [];
        queue.push(data.candidate);
        pendingIceCandidatesRef.current.set(peerUserId, queue);
      }
    };

    socket.on('webrtc:offer', onOffer);
    socket.on('webrtc:answer', onAnswer);
    socket.on('webrtc:ice-candidate', onIceCandidate);

    // Identify all remote peers who are currently in the live call
    const inLiveRemotePeers = participants.filter((p) => p.id !== currentUserId);

    // Clean up connections for participants who left
    const inLiveRemoteIds = new Set(inLiveRemotePeers.map((p) => p.id));
    for (const [peerId, pc] of peerConnectionsRef.current.entries()) {
      if (!inLiveRemoteIds.has(peerId)) {
        console.log(`[WebRTC] Closing peer connection for departed user ${peerId}`);
        pc.close();
        peerConnectionsRef.current.delete(peerId);
        pendingIceCandidatesRef.current.delete(peerId);
        setRemoteStreams((prev) => {
          const next = new Map(prev);
          next.delete(peerId);
          return next;
        });
      }
    }

    // Connect to each in-call remote peer using deterministic tie-breaker
    inLiveRemotePeers.forEach(async (peer) => {
      const peerId = peer.id;
      let pc = peerConnectionsRef.current.get(peerId);
      if (!pc || pc.signalingState === 'closed') {
        pc = createPeerConnection(peerId);

        // Deterministic initiator tie-breaker:
        // Lexicographically greater user ID initiates the offer.
        const shouldInitiate = currentUserId.localeCompare(peerId) > 0;
        if (shouldInitiate) {
          try {
            console.log(`[WebRTC] Initiating video offer to ${peerId}`);
            const offer = await pc.createOffer();
            await pc.setLocalDescription(offer);
            socket.emit('webrtc:offer', {
              roomId,
              targetUserId: peerId,
              sdp: offer,
              streamType: 'video',
            });
          } catch (err) {
            console.warn(`[WebRTC] Failed to create offer to ${peerId}:`, err);
          }
        }
      }
    });

    return () => {
      socket.off('webrtc:offer', onOffer);
      socket.off('webrtc:answer', onAnswer);
      socket.off('webrtc:ice-candidate', onIceCandidate);
    };
  }, [inCall, roomId, currentUserId, participants, createPeerConnection, syncLocalTracksToPeer]);

  return {
    remoteStreams,
  };
}
